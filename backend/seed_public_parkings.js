async function seed() {
  console.log("=== SEEDING PUBLIC PARKING SPOTS ===");
  // 1. Initialize DB to ensure connection and schemas
  await db.initDb();

  // 2. Fetch existing listings to prevent primary key collisions
  const existingListings = await db.dbGetListings() || [];
  const existingIds = new Set(existingListings.map(l => l.id));

  // 3. Seed Owners
  for (const owner of PUBLIC_OWNERS) {
    const existingOwner = await db.dbGetOwner(owner.phone);
    if (!existingOwner) {
      console.log(`[SEED] Adding Owner: ${owner.name} (${owner.phone})`);
      await db.dbSaveOwner(owner);
    } else {
      console.log(`[SEED] Owner already exists: ${owner.name} (${owner.phone})`);
    }
  }

  // 4. Seed Listings
  for (const listing of PUBLIC_LISTINGS) {
    if (!existingIds.has(listing.id)) {
      console.log(`[SEED] Seeding Listing: ${listing.title}`);
      
      // Structure standard data payload matching backend format
      const dataPayload = {
        id: listing.id,
        title: listing.title,
        desc: listing.desc,
        area_landmark: listing.area_landmark,
        price_hourly: listing.price_hourly,
        price_daily: listing.price_daily,
        price_monthly: listing.price_monthly,
        lat: listing.lat,
        lng: listing.lng,
        length: listing.length,
        breadth: listing.breadth,
        amenities: listing.amenities,
        gmap_link: listing.gmap_link,
        gmap_link_regen: listing.gmap_link,
        image: listing.image,
        owner_phone: listing.owner_phone,
        is_sold: listing.is_sold,
        created_at: Date.now() / 1000,
        address_text: listing.address_text
      };

      await db.dbAddListing(dataPayload);
    } else {
      console.log(`[SEED] Listing already exists: ${listing.title}`);
    }
  }

  console.log("[SUCCESS] Seeding complete! Database is populated with public spots.");
}

